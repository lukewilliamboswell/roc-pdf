"""Render the group fixture applications that run grouped case families.

A grouped family is a local package (`tests/<family>/package.roc`) that
exposes one `Cases` module with a closed `Case` type and a `run` dispatch. A
group application wraps the `Case` types of its families in one tag union,
decodes the argv case envelope, checks that it round-trips canonically,
resets the allocation counters, and dispatches. The same renderer writes the
committed `tests/groups/<group>.roc` sources and the single-family
applications that `scripts/test.py --isolate` builds as the equivalence
oracle, so the two differ only in which families they list.

The envelope is `{"case":{"<Tag>":<family case>},"schema_version":2}`.
"""
from __future__ import annotations

import os
from dataclasses import dataclass
from pathlib import Path

ENVELOPE_SCHEMA_VERSION = 2


@dataclass(frozen=True)
class Member:
    """One family in a group application."""

    tag: str
    package: Path


def package_alias(member: Member) -> str:
    """The family's package alias: its directory name, which is snake_case."""
    return member.package.parent.name


def render_group_app(
    name: str,
    app_path: Path,
    platform: Path,
    members: list[Member],
    *,
    inject_allocation: bool = False,
) -> str:
    """The group application's source text.

    `inject_allocation` adds one known allocation inside the measured window,
    for the harness self-test that proves a grouped case's window still
    covers its dispatch; it is never used for committed sources.
    """
    if not members:
        raise ValueError(f"group {name} has no families")
    tags = [member.tag for member in members]
    if len(set(tags)) != len(tags):
        raise ValueError(f"group {name} repeats a family tag")
    base = app_path.parent

    def rel(path: Path) -> str:
        return Path(os.path.relpath(path, base)).as_posix()

    ordered = sorted(members, key=lambda member: member.tag)
    lines = ["app [main!] {", f'\tpf: platform "{rel(platform)}",']
    for member in sorted(ordered, key=package_alias):
        lines.append(f'\t{package_alias(member)}: "{rel(member.package)}",')
    lines.append("}")
    lines.append("")
    lines.append("import pf.Metrics")
    for member in sorted(ordered, key=package_alias):
        lines.append(f"import {package_alias(member)}.Cases as {member.tag}")
    lines.append("")
    lines.append(f"## Fixture group `{name}`: one executable for these case families.")
    lines.append("## Generated by scripts/fixture_groups.py from tests/spec.json; do not edit.")
    lines.append("Case : [")
    for member in ordered:
        lines.append(f"\t{member.tag}({member.tag}.Case),")
    lines.append("]")
    lines.append("")
    lines.append("CaseSpec : { case : Case, schema_version : U64 }")
    lines.append("")
    lines.append("main! : List(Str) => { bytes : List(U8), work : List(U64) }")
    lines.append("main! = |args| {")
    lines.append("\tcase_json = match args.get(1) {")
    lines.append("\t\tOk(text) => text")
    lines.append(f'\t\tErr(OutOfBounds) => crash "CASE_SPEC_MISSING: {name} requires exactly one JSON case argument"')
    lines.append("\t}")
    lines.append("\tif args.len() != 2 {")
    lines.append(f'\t\tcrash "CASE_SPEC_ARITY: {name} requires exactly one JSON case argument"')
    lines.append("\t}")
    lines.append("\tparsed : Try(CaseSpec, [InvalidJson(Str), MissingRequiredField(Str)])")
    lines.append("\tparsed = Json.parse(case_json)")
    lines.append("\tspec = match parsed {")
    lines.append("\t\tOk(value) => value")
    lines.append('\t\tErr(InvalidJson(detail)) => crash "CASE_SPEC_INVALID_JSON: ${detail}"')
    lines.append('\t\tErr(MissingRequiredField(field)) => crash "CASE_SPEC_MISSING_FIELD: ${field}"')
    lines.append("\t}")
    lines.append(f"\tif spec.schema_version != {ENVELOPE_SCHEMA_VERSION} {{")
    lines.append(
        f'\t\tcrash "CASE_SPEC_UNSUPPORTED_VERSION: {name} supports schema_version {ENVELOPE_SCHEMA_VERSION}"'
    )
    lines.append("\t}")
    lines.append("\tif Json.to_str(spec) != case_json {")
    lines.append(f'\t\tcrash "CASE_SPEC_NON_CANONICAL: {name} rejects unknown fields and non-canonical JSON"')
    lines.append("\t}")
    lines.append("\tMetrics.reset_allocations!()")
    if inject_allocation:
        lines.append("\tinjected = List.with_capacity(16).append(spec.schema_version)")
        lines.append("\tif injected.len() != 1 {")
        lines.append('\t\tcrash "INJECTED_ALLOCATION_LOST"')
        lines.append("\t}")
    lines.append("\tmatch spec.case {")
    for member in ordered:
        lines.append(f"\t\t{member.tag}(case) => {member.tag}.run(case)")
    lines.append("\t}")
    lines.append("}")
    return "\n".join(lines) + "\n"
